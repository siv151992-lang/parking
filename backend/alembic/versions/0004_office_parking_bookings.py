def _add_no_overlap_constraint() -> None:
    """Hard guarantee in PostgreSQL: two CONFIRMED / CHECKED_IN bookings of one slot can never overlap.
    Needs the btree_gist extension; if the database user may not create it, the application-level
    check (slot row lock + overlap query) still applies and a warning is printed."""
    bind = op.get_bind()
