# relative traffic per hour of day (office/mall pattern)
HOURLY = [1, 1, 1, 1, 1, 2, 4, 9, 14, 12, 9, 8, 9, 8, 7, 7, 8, 10, 12, 9, 6, 4, 2, 1]


def reset(db):
    for t in ["alerts", "audit_logs", "entry_transactions", "exit_transactions", "parking_sessions", "vehicle_detections", "vehicles"]:
        db.execute(text(f"DELETE FROM {t}"))
    db.execute(text("UPDATE parking_capacity SET alert_state='NORMAL'"))
    db.commit()


def seed_users(db):
    for username, email, name, role, pw in USERS:
        if not db.query(User).filter(User.username == username).first():
            db.add(User(username=username, email=email, full_name=name, role=role, hashed_password=hash_password(pw)))
    db.commit()


def seed_cameras(db) -> dict:
    out = {}
    for c in CAMERAS:
        cam = db.query(Camera).filter(Camera.camera_code == c["camera_code"]).first()
        if not cam:
            cam = Camera(**c, detection_zone=DEFAULT_ZONE, status=CameraStatus.OFFLINE if c.get("is_enabled", True) else CameraStatus.DISABLED)
            db.add(cam)
            db.flush()
        out[c["camera_code"]] = cam.id
    db.commit()
    return out


def seed_vehicles(db, rng):
    existing = db.query(Vehicle).filter(Vehicle.is_reserved.is_(True)).all()
    black = db.query(Vehicle).filter(Vehicle.is_blacklisted.is_(True)).first()
    if existing and black:
        return [v.plate_number for v in existing], black.plate_number
    special = []
    for i in range(6):
        plate = random_plate(rng)
        db.add(Vehicle(plate_number=plate, vehicle_type=VehicleType.CAR, is_reserved=True, owner_name=f"Executive {i + 1}",
                       notes="Reserved bay"))
        special.append(plate)
    bl = random_plate(rng)
    db.add(Vehicle(plate_number=bl, vehicle_type=VehicleType.CAR, is_blacklisted=True, owner_name="Unknown",
                   notes="Reported in previous incident"))
    db.commit()
    return special, bl


def seed_history(db, cams: dict, days: int, rng: random.Random):
    tz = facility_tz(db)
    now_local = datetime.now(tz)
    reserved, blacklisted = seed_vehicles(db, rng)
    regulars = [(random_plate(rng), rng.choices(VehicleType.ALL, [65, 25, 10])[0]) for _ in range(120)] + \
               [(p, VehicleType.CAR) for p in reserved]
    visits = []  # (entry, exit, plate, vtype)
    for d in range(days, -1, -1):
        day = (now_local - timedelta(days=d)).date()
        weekend = day.weekday() >= 5
        daily = int(rng.gauss(55 if weekend else 90, 10))
        for _ in range(max(10, daily)):
            hour = rng.choices(range(24), HOURLY)[0]
            entry = datetime.combine(day, time(hour, rng.randint(0, 59), rng.randint(0, 59)), tzinfo=tz)
            if entry > now_local:
                continue
            plate, vtype = rng.choice(regulars) if rng.random() < 0.55 else (random_plate(rng), rng.choices(VehicleType.ALL, [65, 25, 10])[0])
            stay = timedelta(minutes=max(5, rng.gauss(150 if vtype != VehicleType.COMMERCIAL else 60, 90)))
            visits.append((entry, entry + stay, plate, vtype))
    # a physical vehicle cannot be parked twice at once: drop overlapping visits
    visits.sort(key=lambda v: v[0])
    busy_until: dict[str, datetime] = {}
    events = []  # (ts, camera_code, plate_text, conf, vtype, true_plate)
    for entry, exit_t, plate, vtype in visits:
        if busy_until.get(plate, entry - timedelta(days=1)) + timedelta(minutes=20) > entry:
            continue
        busy_until[plate] = exit_t
        ecam = "CAM-EN-01" if rng.random() < 0.7 else "CAM-EN-02"
        e_text, e_conf = (None, 0.0) if rng.random() < 0.03 else (plate, rng.uniform(0.75, 0.99))
        events.append((entry, ecam, e_text, e_conf, vtype, plate))
        if rng.random() < 0.08:  # vehicle lingered: a second read seconds later (blocked by cooldown/duplicate)
            events.append((entry + timedelta(seconds=rng.randint(5, 40)), ecam, plate, rng.uniform(0.7, 0.95), vtype, plate))
        if exit_t < now_local:
            r = rng.random()
            if r < 0.04:
                x_text = noisy_read(plate, rng)  # OCR confusion -> fuzzy match
            elif r < 0.055:
                x_text = None  # unreadable
            else:
                x_text = plate
            events.append((exit_t, "CAM-EX-01", x_text, rng.uniform(0.72, 0.99) if x_text else 0.0, vtype, plate))
    # a blacklisted visit and an unmatched exit for demo alerts
    t = now_local - timedelta(hours=3)
    events.append((t, "CAM-EN-01", blacklisted, 0.93, VehicleType.CAR, blacklisted))
    events.append((now_local - timedelta(hours=1), "CAM-EX-01", random_plate(rng), 0.9, VehicleType.CAR, None))
    events.sort(key=lambda e: e[0])
    print(f"Replaying {len(events)} vehicle events through the counting engine ...")
    stats = {}
    for i, (ts, code, txt, conf, vtype, _) in enumerate(events):
        ev = DetectionEvent(plate_text=txt, plate_confidence=conf, vehicle_type=vtype, vehicle_confidence=rng.uniform(0.7, 0.98),
                            timestamp=ts.astimezone(timezone.utc), is_simulated=True, track_id=f"seed-{i}", ocr_reads=rng.randint(2, 8))
        res = process_detection(db, cams[code], ev)
        stats[res["status"]] = stats.get(res["status"], 0) + 1
        if i % 500 == 0 and i:
            print(f"  {i}/{len(events)}")
    print("Result:", stats)


def main():
    ap = argparse.ArgumentParser(description="Load sample data")
    ap.add_argument("--days", type=int, default=14)
    ap.add_argument("--reset", action="store_true", help="delete existing operational data first")
    ap.add_argument("--no-history", action="store_true")
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()
    run_migrations()
    bootstrap()
    db = SessionLocal()
    try:
        if args.reset:
            reset(db)
        seed_users(db)
        cams = seed_cameras(db)
        settings_store.invalidate()
        if not args.no_history:
            seed_history(db, cams, args.days, random.Random(args.seed))
        print("Sample data loaded. Logins: admin/Admin@123, manager/Manager@123, operator/Operator@123, viewer/Viewer@123")
    finally:
        db.close()


if __name__ == "__main__":
    main()

