"""Sample data loader.

    python -m app.seed               # users + cameras + 14 days of history
    python -m app.seed --days 30
    python -m app.seed --reset       # wipe ALL operational data first

History is generated by pushing chronologically ordered vehicle events
through the real counting engine (services.counting.process_detection), so
sample data obeys exactly the same duplicate / matching rules as live
traffic. Everything generated here is flagged is_simulated=True / source
SIMULATED, so it is always distinguishable from real camera results.
"""
