export function Thumb({ src, alt, className = "w-16 h-10" }) {
  const [open, setOpen] = useState(false);
  if (!src) return <div className={`${className} rounded bg-slate-100 text-[10px] text-slate-400 flex items-center justify-center`}>no image</div>;
  return (
    <>
      <img src={src} alt={alt} loading="lazy" className={`${className} rounded object-cover cursor-zoom-in ring-1 ring-slate-200`} onClick={(e) => { e.stopPropagation(); setOpen(true); }} />
      {open && (
        <div className="fixed inset-0 z-[60] bg-black/80 flex items-center justify-center p-4" onClick={() => setOpen(false)}>
          <img src={src} alt={alt} className="max-w-full max-h-full rounded-lg" />
        </div>
      )}
    </>
  );
}

