const ToastCtx = createContext(() => {});
export function ToastProvider({ children }) {
  const [toasts, setToasts] = useState([]);
  const push = useCallback((message, type = "info") => {
    const id = Math.random().toString(36).slice(2);
    setToasts((t) => [...t.slice(-4), { id, message, type }]);
    setTimeout(() => setToasts((t) => t.filter((x) => x.id !== id)), type === "error" ? 7000 : 4000);
  }, []);
  const icons = { success: CheckCircle2, error: XCircle, warning: AlertTriangle, info: Info };
  const colors = { success: "text-emerald-600", error: "text-red-600", warning: "text-amber-600", info: "text-blue-600" };
  return (
    <ToastCtx.Provider value={push}>
      {children}
      <div className="fixed bottom-4 right-4 left-4 sm:left-auto z-[70] flex flex-col gap-2 sm:w-96">
        {toasts.map((t) => {
          const I = icons[t.type];
          return (
            <div key={t.id} className="bg-white shadow-lg rounded-lg ring-1 ring-slate-200 px-4 py-3 flex items-start gap-2.5 text-sm">
              <I size={18} className={`${colors[t.type]} shrink-0 mt-px`} />
              <span className="text-slate-700">{t.message}</span>
            </div>
          );
        })}
      </div>
    </ToastCtx.Provider>
  );
}
export const useToast = () => useContext(ToastCtx);

/** Small data-fetch hook. */
export function useFetch(fn, deps = []) {
  const [data, setData] = useState(null);
  const [error, setError] = useState(null);
  const [loading, setLoading] = useState(true);
  const load = useCallback(async () => {
    try {
      setData(await fn());
      setError(null);
    } catch (e) {
      setError(e);
    } finally {
      setLoading(false);
    }
  }, deps); // eslint-disable-line react-hooks/exhaustive-deps
  useEffect(() => {
    setLoading(true);
    load();
  }, [load]);
  return { data, error, loading, reload: load, setData };
}
